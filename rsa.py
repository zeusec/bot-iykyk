# Discord embed limits: field names max 256 chars, field values max 1024
def truncate(text, limit):
    return text[:limit - 3] + "..." if len(text) > limit else text

# Markdown link for real URLs, plain text otherwise ([Source](TEST) renders literally in Discord)
def format_source(source):
    if source and str(source).startswith(("http://", "https://")):
        return f"[Source]({source})"
    return f"Source: {source}" if source else ""

# Price lookup
def get_current_price(ticker):
    url = f"https://api.tradier.com/v1/markets/quotes?symbols={ticker}"
    headers = {"Authorization": f"Bearer {TRADIER_API_KEY}", "Accept": "application/json"}
    try:
        response = requests.get(url, headers=headers, timeout=10)
        response.raise_for_status()
        data = response.json()
        quote = data.get('quotes', {}).get('quote')
        if quote:
            last = quote.get('last')
            return float(last) if last is not None else None
        raise KeyError("The response data did not contain the expected fields.")
    except requests.RequestException as e:
        logging.error(f"Price not found for {ticker}: {e}")
        return None
    except (KeyError, ValueError, TypeError) as e:
        logging.error(f"The response data did not contain the expected fields: {e}")
        return None

# Ticker lookup
def get_company_name(ticker):
    url = f"https://api.tradier.com/v1/markets/lookup?q={ticker}"
    headers = {"Authorization": f"Bearer {TRADIER_API_KEY}", "Accept": "application/json"}
    try:
        response = requests.get(url, headers=headers, timeout=10)
        response.raise_for_status()
        logging.info(f"Successfully received a response for {ticker}. Status Code: {response.status_code}")
        
        data = response.json()
        logging.info(f"API Response: {data}")
        
        securities = data.get('securities')
        if securities:
            security_list = securities.get('security')
            if isinstance(security_list, list):
                for security in security_list:
                    if security.get('symbol') == ticker:
                        exchange_code = security.get('exchange', 'null')
                        exchange_name = EXCH_CODES.get(exchange_code, 'Unknown')
                        return f"({security.get('description', 'null')} @ {exchange_name})"
            elif isinstance(security_list, dict):
                if security_list.get('symbol') == ticker:
                    exchange_code = security_list.get('exchange', 'null')
                    exchange_name = EXCH_CODES.get(exchange_code, 'Unknown')
                    return f"({security_list.get('description', 'null')} @ {exchange_name})"
        
        logging.error("The response data did not contain the expected fields.")
        raise KeyError("The response data did not contain the expected fields.")
        
    except requests.RequestException as e:
        logging.error(f"Company info not found for {ticker}. HTTP Request Exception: {e}")
        return 'null'
        
    except KeyError as e:
        logging.error(f"The response data did not contain the expected fields: {e}")
        return 'null'

# Calculate profit
def calculate_estimated_profit(price: float, split_ratio: str) -> float:
    split_ratio_num = float(split_ratio.split(":")[1]) - 1
    estimated_profit = round(price * split_ratio_num, 2)
    return estimated_profit

# Resolve a ticker to one record: the active "rsa" entry wins, else the newest "past" entry
def find_stock(rsa_data, past_data, ticker):
    for stock in rsa_data:
        if stock['Ticker'].lower() == ticker.lower():
            return stock, "rsa"
    matches = [stock for stock in past_data if stock['Ticker'].lower() == ticker.lower()]
    if matches:
        return max(matches, key=lambda stock: datetime.strptime(stock['Date'], "%m-%d-%Y")), "past"
    return None, None

# Regular market hours, 9:30-16:00 ET weekdays
def market_is_open():
    now = datetime.now(ZoneInfo("America/New_York"))
    return now.weekday() < 5 and (9, 30) <= (now.hour, now.minute) < (16, 0)

# Hourly: archive unconfirmed splits over a week old, then refresh prices during market hours
async def refresh_stock_data():
    while True:
        try:
            rsa_data = read_json_data("rsa")
            cutoff = date.today() - timedelta(days=7)
            kept, expired = [], []
            for stock in rsa_data:
                if datetime.strptime(stock['Date'], "%m-%d-%Y").date() < cutoff:
                    expired.append(stock)
                else:
                    kept.append(stock)
            if expired:
                past_data = read_json_data("past")
                write_json_data("rsa", kept)
                write_json_data("past", past_data + expired)
                logging.info(f"Archived to past (over a week past split date): {', '.join(stock['Ticker'] for stock in expired)}")
            if market_is_open():
                prices = {}
                for ticker in [stock['Ticker'] for stock in kept]:
                    price = await asyncio.to_thread(get_current_price, ticker)
                    if price is not None:
                        prices[ticker] = round(price, 2)
                if prices:
                    stock_data = read_json_data("rsa")
                    for stock in stock_data:
                        if stock['Ticker'] in prices:
                            stock['Current Price'] = prices[stock['Ticker']]
                            stock['Estimated Profit'] = calculate_estimated_profit(prices[stock['Ticker']], stock['Split Ratio'])
                    write_json_data("rsa", stock_data)
        except Exception:
            logging.error("Price refresh cycle failed.", exc_info=True)
        await asyncio.sleep(3600)

refresh_task = None

@listen(Startup)
async def start_price_refresh(event: Startup):
    global refresh_task
    refresh_task = asyncio.create_task(refresh_stock_data())

